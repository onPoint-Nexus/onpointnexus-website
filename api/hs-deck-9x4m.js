// Preserve bytes exactly (deck may contain UTF-8: em-dashes, curly quotes)
const DECK_BYTES = Uint8Array.from(atob(DECK_B64), c => c.charCodeAt(0));

function unauthorized() {
  return new Response('Authentication required.', {
    status: 401,
    headers: {
      'WWW-Authenticate': 'Basic realm="OnPoint Deck", charset="UTF-8"',
      'X-Robots-Tag':     'noindex, nofollow, noarchive',
      'Cache-Control':    'no-store'
    }
  });
}

export default function handler(req) {
  const user = process.env.DECK_USER;
  const pass = process.env.DECK_PASS;

  if (!user || !pass) {
    return new Response('Deck credentials not configured. Set DECK_USER and DECK_PASS.', {
      status: 503,
      headers: { 'Content-Type': 'text/plain', 'X-Robots-Tag': 'noindex, nofollow' }
    });
  }

  const auth = req.headers.get('authorization') || '';
  const expected = 'Basic ' + btoa(user + ':' + pass);

  // Constant-time-ish compare (avoids short-circuit info leak)
  const a = new TextEncoder().encode(auth);
  const b = new TextEncoder().encode(expected);
  let ok = a.length === b.length;
  const len = Math.max(a.length, b.length);
  for (let i = 0; i < len; i++) ok = ok & ((a[i] || 0) === (b[i] || 0));
  if (!ok) return unauthorized();

  return new Response(DECK_BYTES, {
    status: 200,
    headers: {
      'Content-Type':  'text/html; charset=utf-8',
      'X-Robots-Tag':  'noindex, nofollow, noarchive',
      'Cache-Control': 'private, no-store, max-age=0'
    }
  });
}
